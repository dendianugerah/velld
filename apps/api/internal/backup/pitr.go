package backup

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
	"time"
)

// PITRRequest describes a request to recover a PostgreSQL cluster to a point in
// time using a base backup plus archived WAL.
type PITRRequest struct {
	ConnectionID string `json:"connection_id"`
	TargetTime   string `json:"target_time"`
	BaseBackup   string `json:"base_backup"`
}

// PITRConfig is the recovery configuration written next to a restored data
// directory. Postgres 12+ reads recovery settings from postgresql.auto.conf and
// uses the presence of recovery.signal to enter recovery mode.
type PITRConfig struct {
	PostgresqlAutoConf string `json:"postgresql_auto_conf"`
	RecoverySignal     bool   `json:"recovery_signal"`
}

// buildPITRConfig renders the settings that make a cluster replay WAL up to
// targetTime. The restore command copies each requested segment out of the WAL
// archive; recovery_target_time stops replay at the requested instant.
func buildPITRConfig(targetTime time.Time, restoreCommand string) PITRConfig {
	var b strings.Builder

	b.WriteString("# Generated by Velld for point-in-time recovery\n")
	fmt.Fprintf(&b, "restore_command = '%s'\n", escapePostgresConf(restoreCommand))
	fmt.Fprintf(&b, "recovery_target_time = '%s'\n", targetTime.UTC().Format("2006-01-02 15:04:05.000000+00"))
	b.WriteString("recovery_target_action = 'promote'\n")

	return PITRConfig{
		PostgresqlAutoConf: b.String(),
		RecoverySignal:     true,
	}
}

// validatePITRTarget checks a requested target time. It must be parseable and
// in the past; recovering to the future is almost always a mistake.
func validatePITRTarget(raw string, now time.Time) (time.Time, error) {
	if strings.TrimSpace(raw) == "" {
		return time.Time{}, fmt.Errorf("target_time is required")
	}

	parsed, err := parseFlexibleTime(raw)
	if err != nil {
		return time.Time{}, err
	}

	if parsed.After(now) {
		return time.Time{}, fmt.Errorf("target_time %s is in the future", raw)
	}

	return parsed, nil
}

func parseFlexibleTime(raw string) (time.Time, error) {
	layouts := []string{
		time.RFC3339,
		"2006-01-02 15:04:05",
		"2006-01-02T15:04:05",
		"2006-01-02",
	}
	for _, layout := range layouts {
		if t, err := time.Parse(layout, raw); err == nil {
			return t, nil
		}
	}
	return time.Time{}, fmt.Errorf("could not parse time %q", raw)
}

// escapePostgresConf escapes a value for single-quoted use in postgresql.conf.
func escapePostgresConf(value string) string {
	return strings.ReplaceAll(value, "'", "''")
}

// PITRResult reports where a recovery was materialized.
type PITRResult struct {
	DataDir      string `json:"data_dir"`
	TargetTime   string `json:"target_time"`
	RecoveryFile string `json:"recovery_file"`
}

// PrepareRecoveryDir writes the files that make a restored base backup target a
// specific point in time: postgresql.auto.conf with the replay settings and an
// empty recovery.signal. The data directory must already contain the extracted
// base backup. Extracting and starting the server are separate steps so each can
// be tested and run where the binary exists.
func (s *BackupService) PrepareRecoveryDir(dataDir string, targetTime time.Time, restoreCommand string) (*PITRResult, error) {
	cfg := buildPITRConfig(targetTime, restoreCommand)

	autoConfPath := filepath.Join(dataDir, "postgresql.auto.conf")
	if err := os.WriteFile(autoConfPath, []byte(cfg.PostgresqlAutoConf), 0o600); err != nil {
		return nil, fmt.Errorf("write postgresql.auto.conf: %w", err)
	}

	signalPath := filepath.Join(dataDir, "recovery.signal")
	if err := os.WriteFile(signalPath, nil, 0o600); err != nil {
		return nil, fmt.Errorf("write recovery.signal: %w", err)
	}

	return &PITRResult{
		DataDir:      dataDir,
		TargetTime:   targetTime.UTC().Format(time.RFC3339),
		RecoveryFile: autoConfPath,
	}, nil
}
